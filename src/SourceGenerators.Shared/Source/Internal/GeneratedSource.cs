namespace SourceGenerators.Shared.Internal;

/// <summary>
/// 源码生成
/// </summary>
internal static class GeneratedSource {
    /// <summary>
    /// System命名空间
    /// </summary>
    internal const string SystemNamespace = "System";

    /// <summary>
    /// 完整类型显示格式,关闭特殊类型关键字
    /// </summary>
    internal static readonly SymbolDisplayFormat FullFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions( SymbolDisplayMiscellaneousOptions.None );

    /// <summary>
    /// 包裹生成源码:文件头、命名空间、using与主体
    /// </summary>
    internal static string Wrap( string inner, string[] imports, string namespaceName ) {
        if( namespaceName == null )
            throw new ArgumentNullException( nameof( namespaceName ) );
        var builder = new StringBuilder();
        builder.AppendLine( "// <auto-generated/>" );
        builder.AppendLine( "namespace " + namespaceName + ";" );
        builder.AppendLine();
        AppendImports( builder, imports );
        builder.Append( inner.TrimEnd( '\r', '\n' ) );
        builder.AppendLine();
        return builder.ToString();
    }

    /// <summary>
    /// 写入using清单
    /// </summary>
    internal static void AppendImports( StringBuilder builder, string[] imports ) {
        if( imports.Length == 0 )
            return;
        foreach( var name in imports )
            builder.AppendLine( $"using {name};" );
        builder.AppendLine();
    }

    /// <summary>
    /// 写入模块初始化器骨架
    /// </summary>
    internal static void AppendInitializer( StringBuilder builder, string className, string classSummary,
            string registerSummary, IEnumerable<string> lines ) {
        builder.AppendLine( "/// <summary>" );
        builder.AppendLine( $"/// {classSummary}" );
        builder.AppendLine( "/// </summary>" );
        builder.AppendLine( $"internal static class {className} {{" );
        builder.AppendLine( "    /// <summary>" );
        builder.AppendLine( $"    /// {registerSummary}" );
        builder.AppendLine( "    /// </summary>" );
        builder.AppendLine( "    [ModuleInitializer]" );
        builder.AppendLine( "    internal static void Register() {" );
        foreach( var line in lines )
            builder.AppendLine( $"        {line}" );
        builder.AppendLine( "    }" );
        builder.AppendLine( "}" );
    }

    /// <summary>
    /// 泛型定义显示格式,不含类型参数
    /// </summary>
    internal static readonly SymbolDisplayFormat DefinitionFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithGenericsOptions( SymbolDisplayGenericsOptions.None )
        .WithMiscellaneousOptions( SymbolDisplayMiscellaneousOptions.None );

    /// <summary>
    /// 类型完整显示名
    /// </summary>
    internal static string Full( ITypeSymbol type ) {
        return type.ToDisplayString( FullFormat );
    }

    /// <summary>
    /// 泛型定义完整显示名
    /// </summary>
    internal static string FullDefinition( ITypeSymbol type ) {
        return type.ToDisplayString( DefinitionFormat );
    }

    /// <summary>
    /// 类型引用名,已导入时用短名
    /// </summary>
    internal static string Reference( ITypeSymbol type, string[] imports ) {
        if( type is IArrayTypeSymbol array )
            return Reference( array.ElementType, imports ) + "[]";
        if( type is INamedTypeSymbol named && named.IsGenericType ) {
            var definitionName = named.ConstructedFrom.MetadataName;
            var tick = definitionName.IndexOf( '`' );
            var arguments = named.TypeArguments.Select( argument => Reference( argument, imports ) );
            return definitionName.Substring( 0, tick ) + "<" + string.Join( ",", arguments ) + ">";
        }
        var full = Full( type );
        var namespaceName = type.ContainingNamespace?.IsGlobalNamespace == false ? type.ContainingNamespace.ToDisplayString() : NamespaceOf( full );
        return IsImported( namespaceName, imports ) ? ShortName( full, namespaceName ) : full;
    }

    /// <summary>
    /// 取命名空间前缀
    /// </summary>
    private static string NamespaceOf( string full ) {
        var text = RemoveGlobal( full );
        var generic = text.IndexOf( '<' );
        if( generic >= 0 )
            text = text.Substring( 0, generic );
        var index = text.LastIndexOf( '.' );
        return index < 0 ? text : text.Substring( 0, index );
    }

    /// <summary>
    /// 去掉global::前缀
    /// </summary>
    private static string RemoveGlobal( string text ) {
        return text.StartsWith( "global::", StringComparison.Ordinal ) ? text.Substring( 8 ) : text;
    }

    /// <summary>
    /// 命名空间是否已导入,System子命名空间一并视为导入
    /// </summary>
    private static bool IsImported( string name, string[] imports ) {
        foreach( var imported in imports ) {
            if( name == imported )
                return true;
            if( imported == SystemNamespace && name.StartsWith( "System.", StringComparison.Ordinal ) )
                return true;
        }
        return false;
    }

    /// <summary>
    /// 去掉命名空间前缀
    /// </summary>
    private static string ShortName( string full, string namespaceName ) {
        var text = RemoveGlobal( full );
        var prefix = namespaceName + ".";
        return text.StartsWith( prefix, StringComparison.Ordinal ) ? text.Substring( prefix.Length ) : text;
    }

    /// <summary>
    /// 全限定名引用名,已导入时用短名
    /// </summary>
    internal static string Reference( string fullName, string[] imports ) {
        var namespaceName = NamespaceOf( fullName );
        return IsImported( namespaceName, imports ) ? ShortName( fullName, namespaceName ) : fullName;
    }
}
