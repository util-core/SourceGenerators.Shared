#nullable disable

using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace SourceGenerators.Shared.Internal;

/// <summary>
/// 源码生成
/// </summary>
internal static class GeneratedSource {
    /// <summary>
    /// 完整类型显示格式,保留特殊类型关键字与关键字转义
    /// </summary>
    internal static readonly SymbolDisplayFormat FullFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <summary>
    /// 泛型定义显示格式,不含类型参数
    /// </summary>
    internal static readonly SymbolDisplayFormat DefinitionFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithGenericsOptions( SymbolDisplayGenericsOptions.None );

    /// <summary>
    /// 短名显示格式,保留关键字转义
    /// </summary>
    private static readonly SymbolDisplayFormat ShortNameFormat = new SymbolDisplayFormat(
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameOnly,
        genericsOptions: SymbolDisplayGenericsOptions.None,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers );

    /// <summary>
    /// 包裹生成源码,空命名空间表示全局命名空间
    /// </summary>
    internal static string Wrap( string inner, string[] imports, string namespaceName ) {
        if( inner == null )
            throw new ArgumentNullException( nameof( inner ) );
        if( imports == null )
            throw new ArgumentNullException( nameof( imports ) );
        if( namespaceName == null )
            throw new ArgumentNullException( nameof( namespaceName ) );
        if( namespaceName.Length > 0 && namespaceName.Trim().Length == 0 )
            throw new ArgumentException( "命名空间不能为空", nameof( namespaceName ) );
        var builder = new StringBuilder();
        builder.AppendLine( "// <auto-generated/>" );
        if( namespaceName.Length > 0 ) {
            builder.AppendLine( "namespace " + namespaceName + ";" );
            builder.AppendLine();
        }
        AppendImports( builder, imports );
        builder.Append( inner.TrimEnd( '\r', '\n' ) );
        builder.AppendLine();
        return builder.ToString();
    }

    /// <summary>
    /// 写入using清单,跳过空项与空白项
    /// </summary>
    internal static void AppendImports( StringBuilder builder, string[] imports ) {
        if( builder == null )
            throw new ArgumentNullException( nameof( builder ) );
        if( imports == null )
            throw new ArgumentNullException( nameof( imports ) );
        var written = false;
        foreach( var name in imports ) {
            if( string.IsNullOrWhiteSpace( name ) )
                continue;
            builder.AppendLine( $"using {name};" );
            written = true;
        }
        if( written )
            builder.AppendLine();
    }

    /// <summary>
    /// 写入模块初始化器骨架
    /// </summary>
    internal static void AppendInitializer( StringBuilder builder, string className, string classSummary,
            string registerSummary, IEnumerable<string> lines ) {
        if( builder == null )
            throw new ArgumentNullException( nameof( builder ) );
        if( lines == null )
            throw new ArgumentNullException( nameof( lines ) );
        builder.AppendLine( "/// <summary>" );
        builder.AppendLine( $"/// {classSummary}" );
        builder.AppendLine( "/// </summary>" );
        builder.AppendLine( $"internal static class {className} {{" );
        builder.AppendLine( "    /// <summary>" );
        builder.AppendLine( $"    /// {registerSummary}" );
        builder.AppendLine( "    /// </summary>" );
        builder.AppendLine( "    [ModuleInitializer]" );
        builder.AppendLine( "    internal static void Register() {" );
        foreach( var line in lines )
            builder.AppendLine( $"        {line}" );
        builder.AppendLine( "    }" );
        builder.AppendLine( "}" );
    }

    /// <summary>
    /// 类型完整显示名
    /// </summary>
    internal static string Full( ITypeSymbol type ) {
        return type.ToDisplayString( FullFormat );
    }

    /// <summary>
    /// 泛型定义完整显示名
    /// </summary>
    internal static string FullDefinition( ITypeSymbol type ) {
        return type.ToDisplayString( DefinitionFormat );
    }

    /// <summary>
    /// 类型短名,关键字标识符转义
    /// </summary>
    internal static string Short( INamedTypeSymbol type ) {
        return type.ToDisplayString( ShortNameFormat );
    }

    /// <summary>
    /// 类型引用名,命名空间已导入时用短名,未导入时仅限定头部
    /// </summary>
    internal static string Reference( ITypeSymbol type, string[] imports ) {
        if( type == null )
            throw new ArgumentNullException( nameof( type ) );
        if( imports == null )
            throw new ArgumentNullException( nameof( imports ) );
        if( type is IArrayTypeSymbol array )
            return Reference( array.ElementType, imports ) + TypeNameText.ArraySuffix( array.Rank );
        if( type is not INamedTypeSymbol named )
            return Full( type );
        if( IsNullable( named ) )
            return Reference( named.TypeArguments[0], imports ) + "?";
        if( named.SpecialType != SpecialType.None )
            return Full( named );
        var namespaceName = NamespaceName( named );
        var chain = BuildChain( named, imports );
        if( namespaceName != null && IsImported( namespaceName, imports ) )
            return chain;
        return TypeNameText.Qualify( namespaceName == null ? chain : namespaceName + "." + chain );
    }

    /// <summary>
    /// 全限定名引用名,命名空间已导入时用短名,未导入时仅限定头部;裸名原样返回
    /// </summary>
    internal static string Reference( string fullName, string[] imports ) {
        if( fullName == null )
            throw new ArgumentNullException( nameof( fullName ) );
        if( imports == null )
            throw new ArgumentNullException( nameof( imports ) );
        var text = TypeNameText.StripGlobal( fullName );
        var core = TypeNameText.SplitArraySuffix( text, out var suffix );
        return ReferenceText( core, imports ) + suffix;
    }

    /// <summary>
    /// 递归缩短泛型实参
    /// </summary>
    private static string ReferenceText( string text, string[] imports ) {
        var open = text.IndexOf( '<' );
        if( open < 0 )
            return ReferenceCore( text, imports );
        var close = TypeNameText.FindMatchingAngle( text, open );
        if( close < 0 )
            return TypeNameText.Qualify( text );
        var head = text.Substring( 0, open );
        var arguments = TypeNameText.SplitTopLevel( text.Substring( open + 1, close - open - 1 ) )
            .Select( argument => Reference( argument, imports ) );
        return ReferenceCore( head, imports ) + "<" + string.Join( ", ", arguments ) + ">"
            + ReferenceNested( text.Substring( close + 1 ), imports );
    }

    /// <summary>
    /// 缩短嵌套类型后续段的泛型实参
    /// </summary>
    private static string ReferenceNested( string text, string[] imports ) {
        if( text.Length == 0 )
            return string.Empty;
        var builder = new StringBuilder( text.Length );
        var index = 0;
        while( index < text.Length ) {
            var open = text.IndexOf( '<', index );
            if( open < 0 ) {
                builder.Append( text, index, text.Length - index );
                break;
            }
            var close = TypeNameText.FindMatchingAngle( text, open );
            if( close < 0 ) {
                builder.Append( text, index, text.Length - index );
                break;
            }
            builder.Append( text, index, open - index + 1 );
            builder.Append( string.Join( ", ",
                TypeNameText.SplitTopLevel( text.Substring( open + 1, close - open - 1 ) )
                    .Select( argument => Reference( argument, imports ) ) ) );
            builder.Append( '>' );
            index = close + 1;
        }
        return builder.ToString();
    }

    /// <summary>
    /// 单个类型段短名化,未命中导入前缀时补 global:: 限定
    /// </summary>
    private static string ReferenceCore( string segment, string[] imports ) {
        var namespaceName = MatchImportedPrefix( segment, imports );
        if( namespaceName != null ) {
            var remainder = segment.Substring( namespaceName.Length + 1 );
            var dot = TopLevelDot( remainder );
            var generic = remainder.IndexOf( '<' );
            // 仅当剩余部分是顶层类型,或首段本身是泛型类型(命名空间不能带泛型实参)时才可安全剥离
            if( dot < 0 || ( generic >= 0 && generic < dot ) )
                return remainder;
        }
        if( segment.IndexOf( '.' ) < 0 )
            return segment;
        return TypeNameText.Qualify( segment );
    }

    /// <summary>
    /// 查找第一个顶层点号,忽略泛型实参内的点号
    /// </summary>
    private static int TopLevelDot( string text ) {
        var depth = 0;
        for( var index = 0; index < text.Length; index++ ) {
            var current = text[index];
            if( current == '<' )
                depth++;
            else if( current == '>' )
                depth--;
            else if( current == '.' && depth == 0 )
                return index;
        }
        return -1;
    }

    /// <summary>
    /// 匹配最长的已导入命名空间前缀
    /// </summary>
    private static string MatchImportedPrefix( string segment, string[] imports ) {
        string best = null;
        foreach( var imported in imports ) {
            if( string.IsNullOrEmpty( imported ) )
                continue;
            if( segment.Length <= imported.Length || segment[imported.Length] != '.' )
                continue;
            if( segment.StartsWith( imported, StringComparison.Ordinal ) == false )
                continue;
            if( best == null || imported.Length > best.Length )
                best = imported;
        }
        return best;
    }

    /// <summary>
    /// 命名空间是否已导入
    /// </summary>
    private static bool IsImported( string namespaceName, string[] imports ) {
        return imports.Contains( namespaceName, StringComparer.Ordinal );
    }

    /// <summary>
    /// 是否可空值类型
    /// </summary>
    private static bool IsNullable( INamedTypeSymbol type ) {
        return type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
    }

    /// <summary>
    /// 类型所在命名空间,全局命名空间返回null
    /// </summary>
    private static string NamespaceName( INamedTypeSymbol type ) {
        var namespaceSymbol = type.ContainingNamespace;
        return namespaceSymbol == null || namespaceSymbol.IsGlobalNamespace ? null : namespaceSymbol.ToDisplayString();
    }

    /// <summary>
    /// 构建类型链,嵌套类型逐层展开并递归缩短类型实参
    /// </summary>
    private static string BuildChain( INamedTypeSymbol type, string[] imports ) {
        var builder = new StringBuilder();
        if( type.ContainingType != null )
            builder.Append( BuildChain( type.ContainingType, imports ) ).Append( '.' );
        builder.Append( Short( type ) );
        if( type.IsGenericType ) {
            builder.Append( '<' );
            var arguments = type.TypeArguments;
            for( var index = 0; index < arguments.Length; index++ ) {
                if( index > 0 )
                    builder.Append( ", " );
                builder.Append( Reference( arguments[index], imports ) );
            }
            builder.Append( '>' );
        }
        return builder.ToString();
    }
}
