namespace SourceGenerators.Shared.Tests;

/// <summary>
/// 源码生成测试
/// </summary>
public class GeneratedSourceTest {
    /// <summary>
    /// 包裹源码写入文件头、命名空间、using 与主体
    /// </summary>
    [Fact]
    public void TestWrap_WritesHeaderNamespaceImportsAndBody() {
        var text = GeneratedSource.Wrap( "internal class Sample { }", new[] { "System", "Sample.Domain" }, "Sample.Generated" );
        Assert.Contains( "// <auto-generated/>", text );
        Assert.Contains( "namespace Sample.Generated;", text );
        Assert.Contains( "using System;", text );
        Assert.Contains( "using Sample.Domain;", text );
        Assert.Contains( "internal class Sample", text );
        Assert.EndsWith( Environment.NewLine, text );
    }

    /// <summary>
    /// 命名空间为空时抛出异常
    /// </summary>
    [Fact]
    public void TestWrap_ThrowsOnNullNamespace() {
        Assert.Throws<ArgumentNullException>( () => GeneratedSource.Wrap( "x", Array.Empty<string>(), null ) );
    }

    /// <summary>
    /// using 清单按顺序写入并保留尾部空行
    /// </summary>
    [Fact]
    public void TestAppendImports_WritesBlock() {
        var builder = new StringBuilder();
        GeneratedSource.AppendImports( builder, new[] { "System", "Sample.Domain" } );
        var expected = $"using System;{Environment.NewLine}using Sample.Domain;{Environment.NewLine}{Environment.NewLine}";
        Assert.Equal( expected, builder.ToString() );
    }

    /// <summary>
    /// using 清单为空时不写内容
    /// </summary>
    [Fact]
    public void TestAppendImports_EmptyWritesNothing() {
        var builder = new StringBuilder();
        GeneratedSource.AppendImports( builder, Array.Empty<string>() );
        Assert.Equal( string.Empty, builder.ToString() );
    }

    /// <summary>
    /// 模块初始化器骨架包含类声明、特性和注册方法
    /// </summary>
    [Fact]
    public void TestAppendInitializer_WritesSkeleton() {
        var builder = new StringBuilder();
        GeneratedSource.AppendInitializer( builder, "SampleInitializer", "初始化", "注册", new[] { "Sample.Register();" } );
        var text = builder.ToString();
        Assert.Contains( "internal static class SampleInitializer {", text );
        Assert.Contains( "[ModuleInitializer]", text );
        Assert.Contains( "internal static void Register() {", text );
        Assert.Contains( "        Sample.Register();", text );
    }

    /// <summary>
    /// 已导入命名空间的类型用短名,未导入时用全限定名
    /// </summary>
    [Fact]
    public void TestReference_ShortensImportedType() {
        var compilation = TestCompilation.Create( @"namespace Sample.Domain { public class Customer { } }" );
        var type = compilation.GetTypeByMetadataName( "Sample.Domain.Customer" );
        Assert.Equal( "Customer", GeneratedSource.Reference( type, new[] { "Sample.Domain" } ) );
        Assert.Equal( "global::Sample.Domain.Customer", GeneratedSource.Reference( type, Array.Empty<string>() ) );
    }

    /// <summary>
    /// 全限定名字符串按导入清单短名化
    /// </summary>
    [Fact]
    public void TestReference_StringOverload() {
        var fullName = "global::Sample.Domain.Customer";
        Assert.Equal( "Customer", GeneratedSource.Reference( fullName, new[] { "Sample.Domain" } ) );
        Assert.Equal( fullName, GeneratedSource.Reference( fullName, Array.Empty<string>() ) );
    }

    /// <summary>
    /// 数组元素按导入清单短名化
    /// </summary>
    [Fact]
    public void TestReference_Array() {
        var compilation = TestCompilation.Create( @"namespace Sample.Domain { public class Customer { } }" );
        var type = compilation.GetTypeByMetadataName( "Sample.Domain.Customer" );
        var array = compilation.CreateArrayTypeSymbol( type );
        Assert.Equal( "Customer[]", GeneratedSource.Reference( array, new[] { "Sample.Domain" } ) );
    }

    /// <summary>
    /// 完整类型名使用 global:: 限定
    /// </summary>
    [Fact]
    public void TestFull_ReturnsQualifiedName() {
        var compilation = TestCompilation.Create( @"namespace Sample.Domain { public class Customer { } }" );
        var type = compilation.GetTypeByMetadataName( "Sample.Domain.Customer" );
        Assert.Equal( "global::Sample.Domain.Customer", GeneratedSource.Full( type ) );
    }

    /// <summary>
    /// 泛型定义显示名不含类型参数
    /// </summary>
    [Fact]
    public void TestFullDefinition_OmitsTypeParameters() {
        var compilation = TestCompilation.Create( @"namespace Sample.Domain { public class Customer { } }" );
        var list = compilation.GetTypeByMetadataName( "System.Collections.Generic.List`1" );
        Assert.Equal( "global::System.Collections.Generic.List", GeneratedSource.FullDefinition( list ) );
    }
}
